# آيدي روم الأجر المخصص للأذكار
CHANNEL_ID = 1556562624421040208

@bot.event
async def on_ready():
    print(f'Logged in as {bot.user.name} (ID: {bot.user.id})')
    print('Bot is ready and running!')
    if not send_zekr_loop.is_running():
        send_zekr_loop.start()

# مهمة إرسال الأذكار تلقائياً كل ساعة في روم الأجر المحدد
@tasks.loop(hours=1)
async def send_zekr_loop():
    channel = bot.get_channel(CHANNEL_ID)
    if channel:
        data = random.choice(zekrs)
        embed = discord.Embed(
            title=data["title"],
            color=discord.Color.from_rgb(46, 204, 113)
        )
        embed.add_field(name="📖 **الذكر:**", value=data["zekr"], inline=False)
        embed.add_field(name="💬 **الفضل:**", value=data["fadl"], inline=False)
        embed.set_footer(text="تذكير تلقائي بالأذكار • اجعل لسانك رطباً بذكر الله 🤍")
        await channel.send(embed=embed)

